import { defineTable } from "convex/server";
import { v } from "convex/values";

/**
 * PearNotes learning domain (Phase 00.4). Spec: engineering/DATA_MODEL.md.
 *
 * Everything in this file is private by default (engineering/PERMISSIONS.md):
 * `ownerId`/`userId` rows are readable only by the person they belong to, and
 * every read goes through the assertions in convex/learningAuth.ts. None of
 * these tables may ever be auto-seeded — a fresh learner's subjects are
 * EMPTY until they create one or approve an import proposal.
 *
 * Attempts and mastery are personal records kept deliberately separate from
 * the shared `widgets`/`spaces` canvas tables (ARCHITECTURE.md invariant 4).
 */

// engineering/STATE_AND_EVENTS.md — subject lifecycle.
export const subjectStatus = v.union(
  v.literal("manual_empty"),
  v.literal("draft"),
  v.literal("active"),
  v.literal("archived"),
);

export const subjects = defineTable({
  ownerId: v.id("users"),
  name: v.string(),
  avatarId: v.optional(v.string()),
  theme: v.optional(v.string()),
  goal: v.optional(v.string()),
  status: subjectStatus,
  createdAt: v.number(),
  updatedAt: v.number(),
}).index("by_owner", ["ownerId"]);

// ARCHITECTURE.md "Data lifecycle": uploaded / parsing / indexed / failed / deleted.
export const sourceStatus = v.union(
  v.literal("uploaded"),
  v.literal("parsing"),
  v.literal("indexed"),
  v.literal("failed"),
  v.literal("deleted"),
);

/**
 * One uploaded file. The blob lives in Convex file storage; this row is the
 * only durable handle — never store a persistent URL. `sha256` is computed
 * server-side from the stored bytes at registration (convex/sources.ts).
 */
export const sources = defineTable({
  ownerId: v.id("users"),
  storageId: v.id("_storage"),
  title: v.string(),
  mime: v.string(),
  sizeBytes: v.number(),
  sha256: v.string(),
  status: sourceStatus,
  // Extraction failure detail, developer-safe (no document text).
  error: v.optional(v.string()),
  createdAt: v.number(),
  updatedAt: v.number(),
})
  .index("by_owner", ["ownerId"])
  // Upload dedupe + "same file again" hints (INGESTION stage 0, test E06).
  .index("by_owner_sha", ["ownerId", "sha256"])
  // Storage-claim check in sources.register: a storageId already bound to a
  // source row can never be re-registered under a different owner.
  .index("by_storage", ["storageId"]);

/**
 * An addressable slice of a source (page/paragraph). `text` is the private
 * document content: every public read path must pass assertSourceReadable in
 * learningAuth.ts — there is intentionally no way to fetch a segment without
 * resolving its parent source's owner first.
 */
export const sourceSegments = defineTable({
  sourceId: v.id("sources"),
  segmentNo: v.number(),
  page: v.optional(v.number()),
  text: v.string(),
  kind: v.optional(
    v.union(
      v.literal("paragraph"),
      v.literal("heading"),
      v.literal("caption"),
      v.literal("formula"),
    ),
  ),
  // Character offsets into the extracted page text, for quote-level citations.
  quoteStart: v.optional(v.number()),
  quoteEnd: v.optional(v.number()),
  createdAt: v.number(),
})
  .index("by_source", ["sourceId"])
  .index("by_source_number", ["sourceId", "segmentNo"]);

/**
 * Many-to-many: which parts of which sources feed which subject. One file can
 * span several subjects (INGESTION.md multi-subject design). Empty segmentIds
 * means the whole source.
 */
export const subjectSources = defineTable({
  subjectId: v.id("subjects"),
  sourceId: v.id("sources"),
  segmentIds: v.array(v.id("sourceSegments")),
  origin: v.union(
    v.literal("manual"),
    v.literal("ai_proposal"),
    v.literal("user_edit"),
  ),
  createdAt: v.number(),
})
  .index("by_subject", ["subjectId"])
  .index("by_source", ["sourceId"])
  .index("by_subject_source", ["subjectId", "sourceId"]);

/**
 * A citation into an owned source (source-grounding contract, INGESTION.md).
 * Verified server-side before a citation is trusted; "generated by AI" alone
 * is never a citation.
 */
export const sourceRef = v.object({
  sourceId: v.id("sources"),
  segmentId: v.optional(v.id("sourceSegments")),
  page: v.optional(v.number()),
});

export const concepts = defineTable({
  subjectId: v.id("subjects"),
  label: v.string(),
  summary: v.optional(v.string()),
  provenance: v.union(v.literal("ai_proposal"), v.literal("user")),
  sourceRefs: v.array(sourceRef),
  // The curriculum generation that introduced the concept, if any.
  versionId: v.optional(v.id("curriculumVersions")),
  createdAt: v.number(),
}).index("by_subject", ["subjectId"]);

export const objectives = defineTable({
  subjectId: v.id("subjects"),
  conceptIds: v.array(v.id("concepts")),
  // The assessable statement the learner must be able to demonstrate.
  statement: v.string(),
  rubric: v.optional(v.string()),
  createdAt: v.number(),
}).index("by_subject", ["subjectId"]);

// STATE_AND_EVENTS.md — curriculumVersion lifecycle.
export const curriculumState = v.union(
  v.literal("draft"),
  v.literal("validated"),
  v.literal("published"),
  v.literal("superseded"),
  v.literal("rejected"),
);

/**
 * An immutable curriculum generation. At most one `published` head per
 * subject — enforced by the publish mutation (Phase 01) swapping the pointer
 * atomically, not by a constraint here.
 */
export const curriculumVersions = defineTable({
  subjectId: v.id("subjects"),
  version: v.number(),
  state: curriculumState,
  // Set when produced by an ingestion/generation job; undefined for manual.
  generatedFromJobId: v.optional(v.string()),
  createdAt: v.number(),
  publishedAt: v.optional(v.number()),
})
  .index("by_subject", ["subjectId"])
  .index("by_subject_state", ["subjectId", "state"]);

export const sections = defineTable({
  versionId: v.id("curriculumVersions"),
  order: v.number(),
  title: v.string(),
  theme: v.optional(v.string()),
}).index("by_version_order", ["versionId", "order"]);

export const units = defineTable({
  sectionId: v.id("sections"),
  order: v.number(),
  title: v.string(),
}).index("by_section_order", ["sectionId", "order"]);

export const lessons = defineTable({
  unitId: v.id("units"),
  order: v.number(),
  title: v.optional(v.string()),
  objectiveIds: v.array(v.id("objectives")),
  // The canvas this lesson opens on — an ordinary `spaces` row, never a
  // parallel canvas table (ARCHITECTURE.md invariant 2 goes the other way:
  // the canvas must not store learning records).
  canvasSpaceId: v.optional(v.id("spaces")),
  specVersion: v.number(),
  // The exact per-lesson approved citations (from the proposal's
  // sourceSegmentIds) — grounding decisions use these, never subject-wide.
  sourceRefs: v.optional(v.array(sourceRef)),
})
  .index("by_unit_order", ["unitId", "order"])
  .index("by_canvas_space", ["canvasSpaceId"]);

/**
 * Activity specs are a closed discriminated union — typed, never an opaque
 * record (DATA_MODEL.md). New activity kinds extend this union.
 */
export const activitySpec = v.union(
  v.object({
    kind: v.literal("lessonCard"),
    heading: v.string(),
    body: v.string(),
  }),
  v.object({
    kind: v.literal("multipleChoice"),
    prompt: v.string(),
    options: v.array(v.object({ id: v.string(), label: v.string() })),
    // Server-side answer key — set at materialization, NEVER returned by
    // getLesson (stripped before any read). Absent key ⇒ needs_review.
    correctOptionId: v.optional(v.string()),
  }),
  v.object({
    kind: v.literal("shortAnswer"),
    prompt: v.string(),
    expectedAnswer: v.optional(v.string()), // server-only key, stripped on read
  }),
  // Engineer 3 classify widget contract — per-item bucket sort. The correct
  // assignment is server-only (never in the client-facing spec).
  v.object({
    kind: v.literal("classify"),
    prompt: v.string(),
    items: v.array(v.object({ id: v.string(), label: v.string(), caption: v.optional(v.string()) })),
    buckets: v.array(v.object({ id: v.string(), label: v.string(), caption: v.optional(v.string()) })),
    correctAssignments: v.optional(
      v.array(v.object({ itemId: v.string(), bucketId: v.string() })),
    ),
  }),
  v.object({
    kind: v.literal("teachBack"),
    prompt: v.string(),
    rubricCriteria: v.array(v.string()),
  }),
);

export const activities = defineTable({
  lessonId: v.id("lessons"),
  spec: activitySpec,
  objectiveIds: v.array(v.id("objectives")),
  sourceRefs: v.array(sourceRef),
  // Bumped on any spec change; attempts pin the revision they answered so a
  // later edit can never rewrite what a learner actually saw.
  revision: v.number(),
  createdAt: v.number(),
}).index("by_lesson", ["lessonId"]);

export const attemptResponse = v.union(
  v.object({ kind: v.literal("choice"), optionId: v.string() }),
  v.object({ kind: v.literal("text"), text: v.string() }),
  v.object({
    kind: v.literal("classification"),
    assignments: v.array(v.object({ itemId: v.string(), bucketId: v.string() })),
  }),
);

export const attemptEvaluation = v.object({
  verdict: v.union(
    v.literal("correct"),
    v.literal("partial"),
    v.literal("incorrect"),
    v.literal("needs_review"),
  ),
  // 0..1, rubric-graded.
  score: v.optional(v.number()),
  feedback: v.optional(v.string()),
  evaluatedAt: v.number(),
});

/**
 * One immutable submitted answer (STATE_AND_EVENTS.md). Written once at
 * submit time; evaluation is attached exactly once by the grader. Personal:
 * only ever queryable by the userId on the row.
 */
export const attempts = defineTable({
  userId: v.id("users"),
  activityId: v.id("activities"),
  activityRevision: v.number(),
  state: v.union(
    v.literal("submitted"),
    v.literal("evaluated"),
    v.literal("failed"),
  ),
  response: attemptResponse,
  evaluation: v.optional(attemptEvaluation),
  // Client-supplied dedupe key — retries never double-score an answer.
  attemptKey: v.optional(v.string()),
  createdAt: v.number(),
})
  .index("by_user_activity", ["userId", "activityId"])
  .index("by_user_activity_key", ["userId", "activityId", "attemptKey"])
  .index("by_user_time", ["userId", "createdAt"]);

// DATA_MODEL.md — mastery projection, derived from attempt evidence.
export const masteryState = v.union(
  v.literal("not_started"),
  v.literal("learning"),
  v.literal("practicing"),
  v.literal("demonstrated"),
);

/**
 * One row per (userId, objectiveId) — the by_user_objective index is the
 * uniqueness key; writers must upsert through it, never blind-insert.
 */
export const mastery = defineTable({
  userId: v.id("users"),
  objectiveId: v.id("objectives"),
  state: masteryState,
  scoreBand: v.optional(
    v.union(v.literal("low"), v.literal("medium"), v.literal("high")),
  ),
  evidence: v.array(v.object({ attemptId: v.id("attempts"), at: v.number() })),
  updatedAt: v.number(),
})
  .index("by_user_objective", ["userId", "objectiveId"])
  .index("by_user", ["userId"]);

// STATE_AND_EVENTS.md — importJob lifecycle. Ingestion owns these rows end to
// end; proposals stay separate from subjects until the learner approves.
export const importJobState = v.union(
  v.literal("created"),
  v.literal("uploaded"),
  v.literal("extracting"),
  v.literal("classifying"),
  v.literal("needs_review"),
  v.literal("accepted"),
  v.literal("building"),
  v.literal("ready"),
  v.literal("failed"),
  v.literal("cancelled"),
  v.literal("awaiting_model"), // extracted; paid model step gated on owner auth
);

/**
 * One ingestion run over one owned source. `idempotencyKey` makes a retried
 * begin cheap instead of duplicating work (ARCHITECTURE invariant 6).
 */
export const importJobs = defineTable({
  ownerId: v.id("users"),
  sourceId: v.id("sources"),
  idempotencyKey: v.string(),
  state: importJobState,
  error: v.optional(v.string()),
  // Extraction warnings (codes/messages — never document text).
  extractionWarnings: v.optional(v.array(v.string())),
  // Explicit per-job owner consent for a paid model call — the deployment
  // PDF_MODEL_AUTHORIZED flag alone is never sufficient.
  modelAuthorized: v.optional(v.boolean()),
  // Optional focus scope: restrict the model prompt to segments on these
  // physical pages + a topic hint (e.g., pages [1,2], "plant vs animal cells").
  focusPages: v.optional(v.array(v.number())),
  focusHint: v.optional(v.string()),
  // Set atomically by claimModelDispatch the instant a provider call is
  // dispatched — once claimed it can NEVER be re-claimed, so a retry after
  // an ambiguous provider failure can never silently re-spend.
  modelClaimed: v.optional(v.boolean()),
  // Provider facts for audit/eval: model id + prompt version, never secrets.
  model: v.optional(v.string()),
  promptVersion: v.optional(v.number()),
  createdAt: v.number(),
  updatedAt: v.number(),
})
  .index("by_owner", ["ownerId"])
  .index("by_source", ["sourceId"])
  .index("by_owner_key", ["ownerId", "idempotencyKey"])
  .index("by_owner_source_key", ["ownerId", "sourceId", "idempotencyKey"]);

/**
 * The model's structured suggestion, held for review. `proposal` is the
 * validated typed shape in convex/metaProposal.ts — never written into
 * subjects until `state` becomes `accepted` via a learner's explicit action.
 */
// Evidence quotes live in the stored proposal too: each is a verbatim excerpt
// from a cited segment, verified by checkEvidence in convex/metaProposal.ts.
const evidenceQuote = v.object({ segmentId: v.id("sourceSegments"), quote: v.string() });

export const importProposalShape = v.object({
  suggestedSubjects: v.array(
    v.object({
      name: v.string(),
      confidence: v.union(v.literal("high"), v.literal("medium"), v.literal("low")),
      segmentIds: v.array(v.id("sourceSegments")),
      explanation: v.optional(v.string()),
    }),
  ),
  concepts: v.array(
    v.object({
      label: v.string(),
      summary: v.optional(v.string()),
      sourceSegmentIds: v.array(v.id("sourceSegments")),
      evidence: v.array(evidenceQuote),
    }),
  ),
  draftCurriculum: v.optional(
    v.object({
      sections: v.array(
        v.object({
          title: v.string(),
          units: v.array(
            v.object({
              title: v.string(),
              lessons: v.array(
                v.object({
                  title: v.string(),
                  objectives: v.array(v.string()),
                  sourceSegmentIds: v.array(v.id("sourceSegments")),
                  evidence: v.array(evidenceQuote),
                }),
              ),
            }),
          ),
        }),
      ),
    }),
  ),
  warnings: v.array(v.string()),
});

export const importProposals = defineTable({
  jobId: v.id("importJobs"),
  subjectId: v.optional(v.id("subjects")),
  state: v.union(
    v.literal("pending"),
    v.literal("user_edited"),
    v.literal("accepted"),
    v.literal("rejected"),
  ),
  proposal: importProposalShape,
  // Optimistic concurrency token — bump on user edits; review() requires a
  // match so a stale UI can't approve content the learner never saw.
  revision: v.optional(v.number()),
  // Stable ids created by an accepted proposal — makes repeat approvals
  // idempotent returns instead of duplicate materialization.
  materialized: v.optional(
    v.object({
      subjectIds: v.array(v.id("subjects")),
      curriculumVersionIds: v.array(v.id("curriculumVersions")),
    }),
  ),
  createdAt: v.number(),
  updatedAt: v.number(),
}).index("by_job", ["jobId"]);

// STATE_AND_EVENTS.md — proposed/ghost practice branch: proposed until the
// learner accepts or rejects; rejected triggers never silently re-propose.
export const practiceProposals = defineTable({
  ownerId: v.id("users"),
  lessonId: v.id("lessons"),
  /** Deterministic dedupe key (lesson + trigger evidence set). */
  triggerKey: v.string(),
  triggerAttemptIds: v.array(v.id("attempts")),
  rationale: v.string(),
  spec: activitySpec,
  objectiveIds: v.array(v.id("objectives")),
  sourceRefs: v.array(sourceRef),
  state: v.union(
    v.literal("proposed"),
    v.literal("accepted"),
    v.literal("rejected"),
  ),
  createdAt: v.number(),
  updatedAt: v.number(),
})
  .index("by_owner_lesson", ["ownerId", "lessonId"])
  .index("by_trigger", ["triggerKey"]);

// SECURITY_PRIVACY.md — trusted per-item fact→bucket→segment attestation.
// Created only via attestClassificationFacts (internal, human/reviewer
// attestation path — never client-supplied). materializeScoredActivity
// requires an attestation for EVERY scored item; none → abstain, never guess.
export const factAttestations = defineTable({
  templateId: v.string(),
  lessonId: v.id("lessons"),
  itemId: v.string(),
  bucketId: v.string(),
  /** Approved segments a reviewer verified support this fact→bucket. */
  segmentIds: v.array(v.id("sourceSegments")),
  attestedBy: v.string(), // e.g. "owner_review", "reviewer:x"
  createdAt: v.number(),
})
  .index("by_template_lesson", ["templateId", "lessonId"])
  .index("by_lesson", ["lessonId"]);
